# ---------------------------------------------------------------- Table VI
def cost_at(prefix, b, field="answer"):
    for r in COST:
        if r["store_budget"] == b and r["policy"].startswith(prefix):
            return r[field]
    raise KeyError(prefix)


rows = []
for b in sorted({int(r["store_budget"]) for r in COST}):
    vals = {p: cost_at(p, b) for p in ("P0", "RAG", "P1-A", "P1-S")}
    best = max(vals.values())
    cells = " & ".join(f"\\textbf{{{v:.1f}}}" if v == best else f"{v:.1f}"
                       for v in (vals["P0"], vals["RAG"], vals["P1-A"], vals["P1-S"]))
    rows.append(f"{b // 1024} & {cells}" + EOL)
write("cost.tex", r"""\begin{tabular}{@{}rrrrr@{}}
\toprule
Budget (KiB) & P0 & RAG & P1-A & P1-S \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}""")

